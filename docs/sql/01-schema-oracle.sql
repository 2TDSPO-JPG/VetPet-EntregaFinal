CREATE TABLE VP_CREDENCIAL (
    id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    senha_hash  VARCHAR2(100) NOT NULL
);

CREATE TABLE VP_TUTOR (
    id             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR2(120) NOT NULL,
    cpf            VARCHAR2(14),
    email          VARCHAR2(120) NOT NULL UNIQUE,
    telefone       VARCHAR2(20),
    foto_url       VARCHAR2(500),
    cep            VARCHAR2(9),
    logradouro     VARCHAR2(150),
    numero         VARCHAR2(10),
    complemento    VARCHAR2(80),
    bairro         VARCHAR2(80),
    cidade         VARCHAR2(80),
    estado         VARCHAR2(2),
    credencial_id  NUMBER(19) UNIQUE REFERENCES VP_CREDENCIAL (id),
    criado_em      TIMESTAMP NOT NULL,
    ultimo_acesso  TIMESTAMP
);

CREATE TABLE VP_VETERINARIO (
    id                NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome              VARCHAR2(120) NOT NULL,
    cpf               VARCHAR2(14),
    email             VARCHAR2(120) NOT NULL UNIQUE,
    telefone          VARCHAR2(20),
    foto_url          VARCHAR2(500),
    cep               VARCHAR2(9),
    logradouro        VARCHAR2(150),
    numero            VARCHAR2(10),
    complemento       VARCHAR2(80),
    bairro            VARCHAR2(80),
    cidade            VARCHAR2(80),
    estado            VARCHAR2(2),
    credencial_id     NUMBER(19) UNIQUE REFERENCES VP_CREDENCIAL (id),
    crmv              VARCHAR2(20) NOT NULL UNIQUE,
    especialidade     VARCHAR2(80),
    anos_experiencia  NUMBER(10),
    biografia         VARCHAR2(1000),
    criado_em         TIMESTAMP NOT NULL,
    ultimo_acesso     TIMESTAMP
);

CREATE TABLE VP_PET (
    id               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_code         VARCHAR2(12) NOT NULL UNIQUE,
    nome             VARCHAR2(80) NOT NULL,
    data_nascimento  DATE NOT NULL,
    especie          VARCHAR2(20) NOT NULL
                     CHECK (especie IN ('CACHORRO', 'GATO', 'AVE', 'ROEDOR', 'REPTIL', 'OUTRO')),
    raca             VARCHAR2(80),
    sexo             VARCHAR2(10) CHECK (sexo IN ('MACHO', 'FEMEA')),
    peso_kg          NUMBER(6, 2),
    alergias         VARCHAR2(500),
    criado_em        TIMESTAMP NOT NULL
);

CREATE TABLE VP_TUTOR_PET (
    pet_id    NUMBER(19) NOT NULL REFERENCES VP_PET (id),
    tutor_id  NUMBER(19) NOT NULL REFERENCES VP_TUTOR (id),
    PRIMARY KEY (pet_id, tutor_id)
);

CREATE TABLE VP_EXAME (
    id                NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_hora         TIMESTAMP NOT NULL,
    tipo              VARCHAR2(30) NOT NULL,
    motivo            VARCHAR2(500),
    status            VARCHAR2(20) NOT NULL
                      CHECK (status IN ('AGENDADO', 'REALIZADO', 'CANCELADO', 'ADIADO')),
    lembrete_enviado  NUMBER(1) DEFAULT 0 NOT NULL,
    criado_em         TIMESTAMP NOT NULL,
    pet_id            NUMBER(19) NOT NULL REFERENCES VP_PET (id),
    veterinario_id    NUMBER(19) NOT NULL REFERENCES VP_VETERINARIO (id)
);

CREATE TABLE VP_PRONTUARIO (
    id                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exame_id            NUMBER(19) NOT NULL UNIQUE REFERENCES VP_EXAME (id),
    diagnostico         VARCHAR2(2000) NOT NULL,
    prescricao          VARCHAR2(2000),
    exames_solicitados  VARCHAR2(1000),
    observacoes         VARCHAR2(2000),
    peso_aferido_kg     NUMBER(6, 2),
    proximo_retorno     DATE,
    registrado_em       TIMESTAMP NOT NULL,
    atualizado_em       TIMESTAMP
);

CREATE TABLE VP_PERGUNTA (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id          NUMBER(19) NOT NULL REFERENCES VP_PET (id),
    texto           VARCHAR2(1000) NOT NULL,
    autor           VARCHAR2(120),
    resposta        VARCHAR2(2000),
    respondida_por  VARCHAR2(120),
    criada_em       TIMESTAMP NOT NULL,
    respondida_em   TIMESTAMP
);

CREATE TABLE VP_EVENTO_PET (
    id           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id    VARCHAR2(36) NOT NULL UNIQUE,
    pet_id       NUMBER(19) NOT NULL REFERENCES VP_PET (id),
    tipo         VARCHAR2(40) NOT NULL,
    titulo       VARCHAR2(150) NOT NULL,
    descricao    VARCHAR2(1000),
    ocorrido_em  TIMESTAMP NOT NULL
);

CREATE INDEX IX_VP_EXAME_PET_DATA ON VP_EXAME (pet_id, data_hora);
CREATE INDEX IX_VP_EXAME_VET_DATA ON VP_EXAME (veterinario_id, data_hora);
CREATE INDEX IX_VP_EVENTO_PET_DATA ON VP_EVENTO_PET (pet_id, ocorrido_em);
